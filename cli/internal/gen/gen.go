package gen

import (
	"fmt"
	"maps"
	"slices"
	"strings"

	"github.com/sonnes/durabase/cli/internal/migrations"
	"github.com/sonnes/durabase/cli/internal/schema"
)

// Options sets the import paths of the output file.
type Options struct {
	// FunctionsImport is the import path of the functions module, relative
	// to the output file, such as "../durabase/functions". Empty means no
	// functions.
	FunctionsImport string
}

// TypeScript returns the text of durabase.gen.ts.
func TypeScript(snap *schema.Snapshot, files []migrations.File, opts Options) string {
	w := &writer{}
	w.header(opts)
	w.tables(snap)
	w.database(opts)
	w.migrations(files)
	return strings.Join(w.lines, "\n") + "\n"
}

// writer collects the lines of the output file.
type writer struct {
	lines []string
}

func (w *writer) linef(format string, a ...any) {
	w.lines = append(w.lines, fmt.Sprintf(format, a...))
}

func (w *writer) blank() {
	w.lines = append(w.lines, "")
}

func (w *writer) header(opts Options) {
	w.linef("// Generated by `durabase gen`. Do not edit.")
	w.blank()
	if opts.FunctionsImport == "" {
		w.linef(`import type { Migration } from "@durabaseio/sdk";`)
		w.blank()
		return
	}
	w.linef(`import type { FunctionsOf, Migration } from "@durabaseio/sdk";`)
	w.linef("import type * as functions from %s;", quote(opts.FunctionsImport))
	w.blank()
}

// tables writes a type alias, not an interface: an alias fits the index
// signature of TablesShape in @durabaseio/sdk.
func (w *writer) tables(snap *schema.Snapshot) {
	rels := relationships(snap)
	w.linef("export type Tables = {")
	for _, name := range snap.TableNames() {
		w.table(snap.Tables[name], rels[name])
	}
	w.linef("};")
	w.blank()
}

func (w *writer) table(t *schema.Table, rels map[string]string) {
	unions := checkUnions(t)
	w.linef("  %s: {", key(t.Name))

	w.linef("    row: {")
	for _, c := range t.Columns {
		w.linef("      %s: %s;", key(c.Name), rowType(c, unions))
	}
	w.linef("    };")

	w.linef("    insert: {")
	for _, c := range t.Columns {
		if c.Generated() {
			continue
		}
		optional := ""
		if optionalOnInsert(t, c) {
			optional = "?"
		}
		w.linef("      %s%s: %s;", key(c.Name), optional, rowType(c, unions))
	}
	w.linef("    };")

	w.linef("    update: {")
	for _, c := range t.Columns {
		if !c.Generated() {
			w.linef("      %s?: %s;", key(c.Name), rowType(c, unions))
		}
	}
	w.linef("    };")

	w.relationships(rels)
	w.linef("  };")
}

// relationships writes Record<never, never> for a table with no foreign
// keys: an object with no keys allows no embed.
func (w *writer) relationships(rels map[string]string) {
	if len(rels) == 0 {
		w.linef("    relationships: Record<never, never>;")
		return
	}
	w.linef("    relationships: {")
	for _, other := range slices.Sorted(maps.Keys(rels)) {
		w.linef("      %s: %q;", key(other), rels[other])
	}
	w.linef("    };")
}

func (w *writer) database(opts Options) {
	functions := "Record<never, never>"
	if opts.FunctionsImport != "" {
		functions = "FunctionsOf<typeof functions>"
	}
	w.linef("export type Database = {")
	w.linef("  tables: Tables;")
	w.linef("  functions: %s;", functions)
	w.linef("};")
	w.blank()
}

func (w *writer) migrations(files []migrations.File) {
	w.linef("export const migrations: Migration[] = [")
	for _, f := range files {
		w.linef("  {")
		w.linef("    version: %d,", f.Version)
		w.linef("    name: %s,", quote(f.Name))
		w.linef("    statements: [")
		for _, s := range f.Statements {
			w.linef("      %s,", quote(s))
		}
		w.linef("    ],")
		w.linef("  },")
	}
	w.linef("];")
}

// quote returns s as a TypeScript string literal in double quotes.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r == '\n':
			b.WriteString(`\n`)
		case r < 0x20 || r == 0x2028 || r == 0x2029:
			fmt.Fprintf(&b, `\u%04x`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}
